import { test, expect, registerAccount, signIn, backendSnapshot, openCheckIn, saveCheckIn, navigate, addLesson, addManualFood, today } from './helpers';

test('daily weight and notes synchronize across two real devices with one Progress measurement', async ({ app, secondDevice }, testInfo) => {
  const account = await registerAccount(app, testInfo, 'daily');
  await signIn(secondDevice, account);
  const date = await today(app);
  await openCheckIn(app);
  await saveCheckIn(app, '58.3', 'Recorded on the first real device.');
  await expect.poll(async () => (await backendSnapshot(app, account.token)).checkIns.find(item => item.date === date)?.weight).toBe(58.3);
  let state = await backendSnapshot(app, account.token);
  expect(state.weights).toHaveLength(1);
  const weightId = state.weights[0].id;
  const checkInId = state.checkIns[0].id;

  await secondDevice.bringToFront();
  await secondDevice.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(secondDevice.getByRole('button', { name: /^Daily Check-in Complete/ })).toBeVisible();
  await openCheckIn(secondDevice);
  await expect(secondDevice.getByRole('dialog').getByLabel('Notes', { exact: true })).toHaveValue('Recorded on the first real device.');
  await saveCheckIn(secondDevice, '59.4', 'Edited on the second real device.');
  await expect.poll(async () => (await backendSnapshot(secondDevice, account.token)).weights[0]?.weight).toBe(59.4);
  state = await backendSnapshot(secondDevice, account.token);
  expect(state.checkIns).toHaveLength(1);
  expect(state.weights).toHaveLength(1);
  expect(state.checkIns[0]).toEqual(expect.objectContaining({ id: checkInId, weight: 59.4 }));
  expect(state.weights[0]).toEqual(expect.objectContaining({ id: weightId, weight: 59.4 }));

  await app.reload();
  await openCheckIn(app);
  await expect(app.getByRole('dialog').getByLabel('Weight (kg)', { exact: true })).toHaveValue('59.4');
  await expect(app.getByRole('dialog').getByLabel('Notes', { exact: true })).toHaveValue('Edited on the second real device.');
  await app.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await navigate(app, 'Progress');
  expect((await backendSnapshot(app, account.token)).weights).toHaveLength(1);
});

test('real lesson notes support save, edit, completion, reload and deletion', async ({ app }, testInfo) => {
  const account = await registerAccount(app, testInfo, 'lessons');
  await addLesson(app, 'Live technique lesson', 'My original technique note');
  await expect.poll(async () => (await backendSnapshot(app, account.token)).lessons.length).toBe(1);
  await app.getByRole('button', { name: 'Complete Live technique lesson', exact: true }).click();
  await expect.poll(async () => (await backendSnapshot(app, account.token)).lessons[0]?.completed).toBe(true);
  await app.getByRole('button', { name: /Live technique lesson.*My original technique note/ }).click();
  const dialog = app.getByRole('dialog');
  await dialog.getByLabel('Title', { exact: true }).fill('Live edited lesson');
  await dialog.getByLabel('Your notes', { exact: true }).fill('My persisted edited note');
  await dialog.getByRole('button', { name: 'Save Lesson', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect.poll(async () => (await backendSnapshot(app, account.token)).lessons[0]?.notes).toBe('My persisted edited note');
  await app.reload();
  await navigate(app, 'Lessons');
  await app.getByLabel('Search your lessons', { exact: true }).fill('Live edited');
  await app.getByRole('button', { name: /Live edited lesson.*My persisted edited note/ }).click();
  await expect(app.getByRole('dialog').getByLabel('Completed', { exact: true })).toBeChecked();
  await app.getByRole('dialog').getByRole('button', { name: 'Delete Lesson', exact: true }).click();
  await expect(app.getByRole('dialog')).not.toBeVisible();
  await expect.poll(async () => (await backendSnapshot(app, account.token)).lessons.length).toBe(0);
});

test('real manual foods, dated copies and manual nutrition overrides persist', async ({ app }, testInfo) => {
  const account = await registerAccount(app, testInfo, 'foods');
  const date = await today(app);
  await addManualFood(app, 'Live breakfast');
  await expect.poll(async () => (await backendSnapshot(app, account.token)).foodEntries[0]?.calories).toBe(125);
  await app.reload();
  await navigate(app, 'Nutrition');
  await expect(app.getByTestId('calorie-total')).toHaveText('125');
  const breakfast = app.getByRole('button', { name: 'Breakfast', exact: true });
  if (await breakfast.getAttribute('aria-expanded') !== 'true') await breakfast.click();
  await app.getByRole('button', { name: /Live breakfast/ }).click();
  await app.getByRole('dialog').getByLabel('Calories', { exact: true }).fill('175');
  await app.getByRole('dialog').getByRole('button', { name: 'Save Food', exact: true }).click();
  await expect(app.getByRole('dialog')).not.toBeVisible();
  await expect.poll(async () => (await backendSnapshot(app, account.token)).foodEntries[0]?.calories).toBe(175);
  const original = (await backendSnapshot(app, account.token)).foodEntries[0];
  await app.getByRole('button', { name: 'Next day', exact: true }).click();
  await app.getByRole('button', { name: 'Copy food log', exact: true }).click();
  await app.getByRole('dialog').getByLabel('Copy from', { exact: true }).fill(date);
  await app.getByRole('dialog').getByRole('button', { name: 'Copy Food Log', exact: true }).click();
  await expect(app.getByRole('dialog')).not.toBeVisible();
  await expect.poll(async () => (await backendSnapshot(app, account.token)).foodEntries.length).toBe(2);
  const copies = (await backendSnapshot(app, account.token)).foodEntries;
  expect(copies.find(item => item.id === original.id)).toEqual(original);
  expect(new Set(copies.map(item => item.id)).size).toBe(2);
  await app.getByRole('button', { name: 'Nutrition settings', exact: true }).click();
  const targets = app.getByRole('dialog');
  await targets.getByLabel('Calories', { exact: true }).fill('2300');
  await targets.getByLabel('Protein (g)', { exact: true }).fill('125');
  await targets.getByLabel('Carbs (g)', { exact: true }).fill('275');
  await targets.getByLabel('Fat (g)', { exact: true }).fill('65');
  await targets.getByRole('button', { name: 'Save Targets', exact: true }).click();
  await expect(targets).not.toBeVisible();
  await expect.poll(async () => (await backendSnapshot(app, account.token)).targets[0]?.calories).toBe(2300);
  expect((await backendSnapshot(app, account.token)).targets[0]).toEqual(expect.objectContaining({ mode: 'manual', manuallyOverridden: true }));
  await app.getByRole('button', { name: 'Back to Today', exact: true }).click();
  if (await breakfast.getAttribute('aria-expanded') !== 'true') await breakfast.click();
  await app.getByRole('button', { name: /Live breakfast/ }).click();
  await app.getByRole('dialog').getByRole('button', { name: 'Delete Food', exact: true }).click();
  await expect(app.getByRole('dialog')).not.toBeVisible();
  await expect.poll(async () => (await backendSnapshot(app, account.token)).foodEntries.length).toBe(1);
  expect((await backendSnapshot(app, account.token)).foodEntries[0].date).not.toBe(date);
});

test('real food search uses private saved foods and reports unavailable upstream queries', async ({ app }, testInfo) => {
  const account = await registerAccount(app, testInfo, 'food-search');
  await addManualFood(app, 'My private zxb27r meal', '105');
  await expect.poll(async () => (await backendSnapshot(app, account.token)).foodEntries.length).toBe(1);
  await app.getByRole('button', { name: 'Add food to Breakfast', exact: true }).click();
  const search = app.getByRole('dialog').getByLabel('Search foods', { exact: true });
  const searched = app.waitForResponse(response => new URL(response.url()).pathname === '/api/v1/foods/search' && new URL(response.url()).searchParams.get('q') === 'zxb27r');
  await search.fill('zxb27r');
  await search.press('Enter');
  const response = await searched;
  expect(response.status()).toBe(200);
  const result = await response.json();
  const ownFood = result.data.find((item: { name: string }) => item.name === 'My private zxb27r meal');
  expect(ownFood).toBeTruthy();
  expect(ownFood).toEqual(expect.objectContaining({ source: 'Your saved food log', calories: 105 }));
  await expect(app.getByRole('dialog').getByText(/Your saved food log/)).toBeVisible();
  await app.getByRole('dialog').getByRole('button', { name: /My private zxb27r meal/ }).click();
  const editor = app.getByRole('dialog');
  await editor.getByLabel('Quantity', { exact: true }).fill('2');
  await editor.getByRole('button', { name: 'Save Food', exact: true }).click();
  await expect(editor).not.toBeVisible();
  await expect.poll(async () => (await backendSnapshot(app, account.token)).foodEntries.length).toBe(2);
  const saved = (await backendSnapshot(app, account.token)).foodEntries;
  expect(saved.find(item => item.source === 'database')).toEqual(expect.objectContaining({ foodId: ownFood.id, quantity: 2, calories: ownFood.calories * 2 }));

  await app.getByRole('button', { name: 'Add food to Breakfast', exact: true }).click();
  const query = `unmatched-${account.userId}`;
  const unavailable = app.waitForResponse(response => new URL(response.url()).pathname === '/api/v1/foods/search' && new URL(response.url()).searchParams.get('q') === query);
  await search.fill(query);
  await search.press('Enter');
  expect((await unavailable).status(), 'The local unavailable upstream must produce a real API error').toBe(503);
  const dialog = app.getByRole('dialog');
  await expect(dialog.getByRole('alert')).toContainText(/unavailable|try.*later/i);
  await expect(dialog.getByRole('button', { name: /My private zxb27r meal/ })).not.toBeVisible();
  expect((await backendSnapshot(app, account.token)).foodEntries).toEqual(saved);
});
